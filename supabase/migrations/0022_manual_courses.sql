-- XFunction: real per-user courses, replacing lib/mock-canvas-data.ts's
-- hardcoded mockCourses as the app's source of truth. Run this once in
-- the Supabase dashboard's SQL Editor, after 0021_support_chat_usage.sql.
--
-- courses.id is TEXT and APP-SUPPLIED (not database-generated) — for a
-- genuinely manual course the app generates a fresh crypto.randomUUID(),
-- but when a student clicks "Load demo data" (see lib/user-courses.ts's
-- seedDemoData()), the three seeded courses keep their ORIGINAL ids from
-- lib/mock-canvas-data.ts ("ap-biology", "us-history", "algebra-2").
-- That's deliberate: lib/grade-history.ts's fabricated weekly trend and
-- lib/mock-announcements.ts's fabricated class announcements are both
-- keyed by those exact literal ids — reusing them means demo-seeded
-- courses keep that flavor content working with no special-casing
-- ("this course happens to have canned history" instead of "this
-- course is secretly flagged as demo"), while genuinely manual courses
-- (fresh UUIDs, never in those lookup tables) naturally get the honest
-- fallback behavior (a single real current-value point, no
-- announcements) those two files already degrade to for any unknown id.
create table if not exists courses (
  id text primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  credit_hours numeric not null default 1.0,
  grading_scale text not null default 'standard' check (grading_scale in ('standard', 'simple')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table courses enable row level security;

create policy "Users manage their own courses"
  on courses
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- The /parent read-only dashboard (see app/parent/page.tsx) needs to
-- read a LINKED STUDENT's real courses, not just the signed-in parent's
-- own — parent_links (0012_parent_links.sql) deliberately grants no
-- cross-user read on any other table, by design, so without this a
-- parent's session (auth.uid() = the parent, not the student) would
-- just see nothing here, silently. This mirrors that same "active,
-- accepted link only" condition rather than introducing a new access
-- model.
create policy "Parents can view their linked student's courses"
  on courses
  for select
  using (
    exists (
      select 1 from parent_links pl
      where pl.student_id = courses.user_id
        and pl.parent_id = auth.uid()
        and pl.status = 'active'
    )
  );

-- integer identity (not uuid) so group/assignment ids stay real JS
-- numbers end-to-end — matches CanvasAssignmentGroup.id / CanvasAssignment.id's
-- existing `number` type in lib/canvas-types.ts (which the whole grade
-- calculator is built against), so nothing downstream needs widening to
-- accept string ids. bigint was considered and rejected: PostgREST
-- serializes bigint columns as strings to avoid JS float precision loss,
-- which would have reintroduced exactly the type mismatch this avoids.
create table if not exists assignment_groups (
  id integer generated by default as identity primary key,
  course_id text not null references courses(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  weight numeric not null,
  position int not null default 0,
  created_at timestamptz not null default now()
);

alter table assignment_groups enable row level security;

create policy "Users manage their own assignment groups"
  on assignment_groups
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- Same parent read-through as courses above — see that policy's comment.
create policy "Parents can view their linked student's assignment groups"
  on assignment_groups
  for select
  using (
    exists (
      select 1 from parent_links pl
      where pl.student_id = assignment_groups.user_id
        and pl.parent_id = auth.uid()
        and pl.status = 'active'
    )
  );

create table if not exists assignments (
  id integer generated by default as identity primary key,
  group_id integer not null references assignment_groups(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  points_possible numeric not null,
  due_at timestamptz,
  -- null = ungraded, matching CanvasAssignment.submission being absent
  -- entirely for ungraded work (see lib/user-courses.ts's mapping).
  score numeric,
  created_at timestamptz not null default now()
);

alter table assignments enable row level security;

create policy "Users manage their own assignments"
  on assignments
  for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- Same parent read-through as courses above — see that policy's comment.
create policy "Parents can view their linked student's assignments"
  on assignments
  for select
  using (
    exists (
      select 1 from parent_links pl
      where pl.student_id = assignments.user_id
        and pl.parent_id = auth.uid()
        and pl.status = 'active'
    )
  );

create index if not exists assignment_groups_course_idx on assignment_groups (course_id);
create index if not exists assignments_group_idx on assignments (group_id);
